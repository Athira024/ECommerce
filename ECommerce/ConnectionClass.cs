            con = new SqlConnection(@"server=LAPTOP-JV3FS7B9\SQLEXPRESS;database=Ebuy;Integrated Security=true");
        }
        public int Fn_Exenonquery(string sqlquery) //insert,delete,update
        {
            if (con.State == ConnectionState.Open)
            {
                con.Close();
            }
            cmd = new SqlCommand(sqlquery, con);
            con.Open();
            int i = cmd.ExecuteNonQuery();
            con.Close();
            return i;
        }
        public string Fn_Exescalar(string sqlquery) //select
        {
            if (con.State == ConnectionState.Open)
